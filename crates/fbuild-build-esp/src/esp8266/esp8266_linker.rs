//! ESP8266 linker implementation.
//!
//! Links ESP8266 object files into `firmware.elf`, converts it to the
//! eboot + sketch `firmware.bin` ([`super::elf2bin`]), and reports size.
//!
//! Key differences from AVR:
//! - SDK precompiled libraries from `tools/sdk/lib/`
//! - Linker script from the board JSON `ldscript` field, resolved in `tools/sdk/ld/`
//! - Firmware image built in-process like the core's `tools/elf2bin.py`

use std::path::{Path, PathBuf};

use fbuild_core::subprocess::run_command;
use fbuild_core::{BuildProfile, Result, SizeInfo};

use super::mcu_config::Esp8266McuConfig;
use crate::linker::{LinkExtraArgs, Linker, LinkerScripts};

/// Generation of the firmware image recipe (linker-script rewrite + elf2bin);
/// part of the build and link fingerprints so stale images are relinked when it
/// changes.
pub(crate) const IMAGE_GENERATION: &str = "2";

/// ESP8266-specific linker using Xtensa LX106 GCC as the link driver.
pub struct Esp8266Linker {
    gcc_path: PathBuf,
    ar_path: PathBuf,
    objcopy_path: PathBuf,
    size_path: PathBuf,
    /// Path to `tools/sdk/lib/` inside the framework.
    sdk_lib_dir: PathBuf,
    /// Path to `tools/sdk/lib/NONOSDK305/` â€” NonOS SDK version-specific libraries.
    sdk_nonosdk_lib_dir: PathBuf,
    /// Path to `tools/sdk/ld/` â€” needed by `generate_linker_scripts()` for template lookup.
    sdk_ld_dir: PathBuf,
    /// Board linker script + search directories.
    linker_scripts: LinkerScripts,
    mcu_config: Esp8266McuConfig,
    profile: BuildProfile,
    flash_mode: String,
    flash_freq: String,
    max_flash: Option<u64>,
    max_ram: Option<u64>,
    verbose: bool,
    /// Arduino's `eboot.elf`, written ahead of the sketch at flash 0x0.
    eboot_elf: PathBuf,
}

impl Esp8266Linker {
    #[allow(clippy::too_many_arguments)]
    pub fn new(
        gcc_path: PathBuf,
        ar_path: PathBuf,
        objcopy_path: PathBuf,
        size_path: PathBuf,
        sdk_lib_dir: PathBuf,
        sdk_nonosdk_lib_dir: PathBuf,
        sdk_ld_dir: PathBuf,
        linker_scripts: LinkerScripts,
        mcu_config: Esp8266McuConfig,
        profile: BuildProfile,
        flash_mode: Option<String>,
        flash_freq: &str,
        max_flash: Option<u64>,
        max_ram: Option<u64>,
        verbose: bool,
    ) -> Self {
        let flash_mode =
            flash_mode.unwrap_or_else(|| mcu_config.esptool.default_flash_mode.clone());
        Self {
            gcc_path,
            ar_path,
            objcopy_path,
            size_path,
            sdk_lib_dir,
            sdk_nonosdk_lib_dir,
            sdk_ld_dir,
            linker_scripts,
            mcu_config,
            profile,
            flash_mode,
            flash_freq: flash_freq.to_string(),
            max_flash,
            max_ram,
            verbose,
            eboot_elf: PathBuf::new(),
        }
    }

    /// Builder: the framework's `bootloaders/eboot/eboot.elf`.
    pub fn with_eboot_elf(mut self, eboot_elf: PathBuf) -> Self {
        self.eboot_elf = eboot_elf;
        self
    }
}

impl Esp8266Linker {
    /// Preprocess `eagle.app.v6.common.ld.h` â†’ `local.eagle.app.v6.common.ld`.
    ///
    /// The board linker script (e.g. `eagle.flash.4m1m.ld`) includes
    /// `local.eagle.app.v6.common.ld` via the linker's `INCLUDE` directive.
    /// This file doesn't ship pre-built â€” it must be generated by running
    /// the GCC preprocessor on the `.ld.h` template with the correct defines.
    async fn generate_linker_scripts(&self, output_dir: &Path) -> Result<()> {
        let ld_template = self.sdk_ld_dir.join("eagle.app.v6.common.ld.h");
        if !ld_template.exists() {
            return Err(fbuild_core::FbuildError::BuildFailed(format!(
                "ESP8266 linker script template not found: {}",
                ld_template.display()
            )));
        }
        let output_ld = output_dir.join("local.eagle.app.v6.common.ld");

        let mut args: Vec<String> = vec![self.gcc_path.to_string_lossy().to_string()];
        args.extend(["-CC".to_string(), "-E".to_string(), "-P".to_string()]);

        // Pass all MCU defines (VTABLES_IN_FLASH, MMU_IRAM_SIZE, etc.)
        for entry in &self.mcu_config.defines {
            match entry {
                crate::esp32::mcu_config::DefineEntry::Simple(name) => {
                    args.push(format!("-D{name}"));
                }
                crate::esp32::mcu_config::DefineEntry::KeyValue(name, value) => {
                    args.push(format!("-D{name}={value}"));
                }
            }
        }
        // FP_IN_IROM: place float printf/scanf in flash (required by the .ld.h template)
        args.push("-DFP_IN_IROM".to_string());

        args.push(ld_template.to_string_lossy().to_string());
        args.extend(["-o".to_string(), output_ld.to_string_lossy().to_string()]);

        let args_ref: Vec<&str> = args.iter().map(|s| s.as_str()).collect();
        // FastLED/fbuild#809: linker-script preprocessing is trivial;
        // bound to 30s.
        let result = run_command(
            &args_ref,
            None,
            None,
            Some(std::time::Duration::from_secs(30)),
        )
        .await?;
        if !result.success() {
            return Err(fbuild_core::FbuildError::BuildFailed(format!(
                "ESP8266 linker script preprocessing failed:\n{}",
                result.stderr
            )));
        }
        let script = std::fs::read_to_string(&output_ld)?;
        std::fs::write(&output_ld, hashed_object_patterns(&script))?;
        tracing::info!("generated local.eagle.app.v6.common.ld");
        Ok(())
    }
}

/// Rewrite literal object names in `EXCLUDE_FILE (...)` lists to match the
/// hashed names fbuild emits (`umm_malloc.cpp` → `umm_malloc_335c.cpp.o`, see
/// `CompilerBase::object_path`).
///
/// The core script keeps `umm_malloc.cpp.o` out of flash with
/// `EXCLUDE_FILE (umm_malloc.cpp.o)` because `umm_init` runs before the flash
/// cache is mapped. A literal name never matches the hashed object, so
/// `umm_init` landed in irom and the board looped on `Fatal exception (0)`.
fn hashed_object_patterns(script: &str) -> String {
    const OPEN: &str = "EXCLUDE_FILE (";
    let mut out = String::with_capacity(script.len());
    let mut rest = script;
    while let Some(start) = rest.find(OPEN) {
        let body_start = start + OPEN.len();
        let Some(len) = rest[body_start..].find(')') else {
            break;
        };
        out.push_str(&rest[..body_start]);
        let names: Vec<String> = rest[body_start..body_start + len]
            .split_whitespace()
            .map(hashed_object_pattern)
            .collect();
        out.push_str(&names.join(" "));
        rest = &rest[body_start + len..];
    }
    out.push_str(rest);
    out
}

/// `umm_malloc.cpp.o` → `umm_malloc.cpp.o *umm_malloc_????.cpp.o` (the literal
/// name is kept); wildcard patterns and names that aren't `<stem>.<ext>.o` are
/// left alone.
fn hashed_object_pattern(name: &str) -> String {
    if name.contains(['*', '?', '/', ':']) {
        return name.to_string();
    }
    match name.strip_suffix(".o").and_then(|n| n.rsplit_once('.')) {
        Some((stem, ext)) if !stem.is_empty() => format!("{name} *{stem}_????.{ext}.o"),
        _ => name.to_string(),
    }
}

#[async_trait::async_trait]
impl Linker for Esp8266Linker {
    /// Everything `link` and `generate_linker_scripts` read besides objects and
    /// `LinkExtraArgs`. Built field by field: `mcu_config.profiles` is a
    /// `HashMap`, so its `Debug` order isn't stable across processes.
    fn link_fingerprint(&self) -> String {
        let profile_flags = self
            .mcu_config
            .profiles
            .get(self.profile.as_dir_name())
            .map(|p| p.link_flags.clone())
            .unwrap_or_default();
        format!(
            "esp8266-image-{IMAGE_GENERATION}|{:?}|{:?}|{:?}|{:?}|{:?}|{:?}|{:?}|{:?}|{:?}",
            self.gcc_path,
            self.mcu_config.linker_flags,
            profile_flags,
            self.mcu_config.linker_libs,
            self.mcu_config.defines,
            self.linker_scripts,
            self.sdk_lib_dir,
            self.sdk_nonosdk_lib_dir,
            self.sdk_ld_dir,
        )
    }

    async fn archive(&self, objects: &[PathBuf], output: &Path) -> Result<()> {
        crate::linker::LinkerBase::archive(&self.ar_path, objects, output, "xtensa-lx106-elf-ar")
            .await
    }

    async fn link(
        &self,
        objects: &[PathBuf],
        archives: &[PathBuf],
        output_dir: &Path,
        extra: &LinkExtraArgs,
    ) -> Result<PathBuf> {
        std::fs::create_dir_all(output_dir)?;

        // Preprocess linker script template before linking
        self.generate_linker_scripts(output_dir).await?;

        let elf_path = output_dir.join("firmware.elf");
        let mut positional_archives: Vec<PathBuf> = archives
            .iter()
            .filter(|path| {
                path.extension()
                    .and_then(|ext| ext.to_str())
                    .map(|ext| ext.eq_ignore_ascii_case("a"))
                    .unwrap_or(false)
            })
            .cloned()
            .collect();
        let loose_objects: Vec<PathBuf> = archives
            .iter()
            .filter(|path| {
                !path
                    .extension()
                    .and_then(|ext| ext.to_str())
                    .map(|ext| ext.eq_ignore_ascii_case("a"))
                    .unwrap_or(false)
            })
            .cloned()
            .collect();

        if !loose_objects.is_empty() {
            let bundled_archive = output_dir.join("libfbuild-core.a");
            self.archive(&loose_objects, &bundled_archive).await?;
            positional_archives.insert(0, bundled_archive);
        }

        let mut args: Vec<String> = vec![self.gcc_path.to_string_lossy().to_string()];

        // Linker flags from config
        args.extend(self.mcu_config.linker_flags.iter().cloned());

        // Profile-specific link flags
        if let Some(profile) = self.mcu_config.profiles.get(self.profile.as_dir_name()) {
            args.extend(profile.link_flags.iter().cloned());
        }
        args.extend(extra.flags.iter().cloned());

        // Build output dir â€” contains generated local.eagle.app.v6.common.ld
        args.push(format!("-L{}", output_dir.to_string_lossy()));
        // Board linker script + SDK ld search directory
        args.extend(self.linker_scripts.to_args());

        // PlatformIO relies on GCC's built-in search path for libc/libstdc++;
        // only the framework SDK directories are added explicitly here.
        args.push(format!("-L{}", self.sdk_lib_dir.to_string_lossy()));
        args.push(format!("-L{}", self.sdk_nonosdk_lib_dir.to_string_lossy()));

        args.extend(["-o".to_string(), elf_path.to_string_lossy().to_string()]);

        // Always emit a linker map next to firmware.elf for debugging (#305).
        let map_path = output_dir.join("firmware.map");
        args.push(format!("-Wl,-Map={}", map_path.to_string_lossy()));

        // Sketch objects first
        for obj in objects {
            args.push(obj.to_string_lossy().to_string());
        }

        // PlatformIO links the core archive inside the linker group together with
        // the SDK libraries. Keeping it outside the group leaves later SDK/core
        // cross-references like `settimeofday` unresolved.
        args.push("-Wl,--start-group".to_string());
        for archive in &positional_archives {
            args.push(archive.to_string_lossy().to_string());
        }
        args.extend(self.mcu_config.linker_libs.iter().cloned());
        args.extend(extra.libs.iter().cloned());
        args.push("-Wl,--end-group".to_string());

        if self.verbose {
            tracing::debug!(target: "fbuild_build::linker::esp8266", "link: {}", args.join(" "));
        }

        let args_ref: Vec<&str> = args.iter().map(|s| s.as_str()).collect();
        // FastLED/fbuild#809: bound the link step at 3 min.
        let result = run_command(
            &args_ref,
            None,
            None,
            Some(std::time::Duration::from_secs(180)),
        )
        .await?;

        if !result.success() {
            return Err(fbuild_core::FbuildError::BuildFailed(format!(
                "xtensa-lx106-elf-gcc link failed:\n{}",
                result.stderr
            )));
        }

        Ok(elf_path)
    }

    async fn convert_firmware(&self, elf_path: &Path, output_dir: &Path) -> Result<PathBuf> {
        // Arduino-ESP8266's image is eboot + sketch (`tools/elf2bin.py`). There
        // is no fallback: an `objcopy -O binary` dump flashes "successfully"
        // and then never boots.
        let bin_path = output_dir.join("firmware.bin");
        let read = |path: &Path| {
            std::fs::read(path).map_err(|e| {
                fbuild_core::FbuildError::BuildFailed(format!(
                    "ESP8266 elf2bin: cannot read {}: {e}",
                    path.display()
                ))
            })
        };
        // `max_flash` is the board's flash chip size; the MCU JSON default
        // ("4MB") covers boards that omit it.
        let flash_size = self.max_flash.unwrap_or_else(|| {
            let default = &self.mcu_config.esptool.default_flash_size;
            default
                .strip_suffix("MB")
                .and_then(|mb| mb.parse::<u64>().ok())
                .map_or(4 << 20, |mb| mb << 20)
        });
        let image = super::elf2bin::elf2bin(
            &read(&self.eboot_elf)?,
            &read(elf_path)?,
            &self.flash_mode,
            &self.flash_freq,
            flash_size,
        )?;
        std::fs::write(&bin_path, &image).map_err(|e| {
            fbuild_core::FbuildError::BuildFailed(format!(
                "failed to write {}: {e}",
                bin_path.display()
            ))
        })?;
        tracing::info!(
            "converted ELF -> firmware.bin (eboot + sketch, {} bytes)",
            image.len()
        );
        Ok(bin_path)
    }

    fn size_tool_path(&self) -> &Path {
        &self.size_path
    }

    fn ar_tool_path(&self) -> Option<&Path> {
        Some(&self.ar_path)
    }

    fn objcopy_tool_path(&self) -> Option<&Path> {
        Some(&self.objcopy_path)
    }

    fn link_driver_path(&self) -> Option<&Path> {
        Some(&self.gcc_path)
    }

    async fn report_size(&self, elf_path: &Path) -> Result<SizeInfo> {
        crate::linker::LinkerBase::report_size(
            &self.size_path,
            elf_path,
            self.max_flash,
            self.max_ram,
            "xtensa-lx106-elf-size",
        )
        .await
    }
}

#[cfg(test)]
mod tests {
    #[test]
    fn exclude_file_names_match_hashed_objects() {
        let script = "    *.cpp.o(EXCLUDE_FILE (umm_malloc.cpp.o) .literal* EXCLUDE_FILE (umm_malloc.cpp.o) .text*)\n    KEEP (*(EXCLUDE_FILE (*crtend.o) .ctors))\n";
        assert_eq!(
            super::hashed_object_patterns(script),
            "    *.cpp.o(EXCLUDE_FILE (umm_malloc.cpp.o *umm_malloc_????.cpp.o) .literal* EXCLUDE_FILE (umm_malloc.cpp.o *umm_malloc_????.cpp.o) .text*)\n    KEEP (*(EXCLUDE_FILE (*crtend.o) .ctors))\n"
        );
    }

    #[test]
    fn hashed_pattern_leaves_non_object_names() {
        assert_eq!(super::hashed_object_pattern("crtend.o"), "crtend.o");
        assert_eq!(super::hashed_object_pattern("*crtend.o"), "*crtend.o");
        assert_eq!(super::hashed_object_pattern("a.c.o"), "a.c.o *a_????.c.o");
    }

    use super::*;
    use crate::esp8266::mcu_config::get_esp8266_config;

    #[test]
    fn test_esp8266_linker_creation() {
        let linker = Esp8266Linker::new(
            PathBuf::from("/bin/xtensa-lx106-elf-gcc"),
            PathBuf::from("/bin/xtensa-lx106-elf-ar"),
            PathBuf::from("/bin/xtensa-lx106-elf-objcopy"),
            PathBuf::from("/bin/xtensa-lx106-elf-size"),
            PathBuf::from("/sdk/lib"),
            PathBuf::from("/sdk/lib/NONOSDK305"),
            PathBuf::from("/sdk/ld"),
            LinkerScripts::single(PathBuf::from("/sdk/ld"), "eagle.flash.4m1m.ld"),
            get_esp8266_config().unwrap(),
            BuildProfile::Release,
            Some("dio".to_string()),
            "40m",
            Some(4_194_304),
            Some(81_920),
            false,
        );
        assert!(
            linker
                .linker_scripts
                .scripts
                .iter()
                .any(|s| s.contains("eagle.flash.4m1m"))
        );
        assert_eq!(linker.max_flash, Some(4_194_304));
        assert_eq!(linker.max_ram, Some(81_920));
        assert_eq!(linker.flash_mode, "dio");
    }
}
